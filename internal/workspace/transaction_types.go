// FailureInjector is used only to make filesystem and crash boundaries
// deterministic in tests. Production callers omit it.
type FailureInjector func(FailurePoint, int) error

// TransactionOption configures a TransactionManager.
type TransactionOption func(*transactionOptions) error

type transactionOptions struct {
	now      func() time.Time
	injector FailureInjector
	timeout  time.Duration
}

// WithTransactionTimeout narrows the manager-owned maximum duration. It is
// primarily useful for deterministic tests; production uses the fixed five
// minute upper bound.
func WithTransactionTimeout(timeout time.Duration) TransactionOption {
	return func(options *transactionOptions) error {
		if timeout <= 0 || timeout > maximumTransactionTime {
			return errors.New("native edit transaction timeout is invalid")
		}
		options.timeout = timeout
		return nil
	}
}

// WithTransactionClock supplies a controllable UTC clock for tests.
func WithTransactionClock(now func() time.Time) TransactionOption {
	return func(options *transactionOptions) error {
		if now == nil {
			return errors.New("native edit clock is required")
		}
		options.now = now
		return nil
	}
}

// WithFailureInjector supplies deterministic failure boundaries for tests.
func WithFailureInjector(injector FailureInjector) TransactionOption {
	return func(options *transactionOptions) error {
		if injector == nil {
			return errors.New("native edit failure injector is required")
		}
		options.injector = injector
		return nil
	}
}

// JournalPhase is a durable, secret-free edit phase.
type JournalPhase string

const (
	JournalStaging    JournalPhase = "staging"
	JournalPrepared   JournalPhase = "prepared"
	JournalReplacing  JournalPhase = "replacing"
	JournalFinalizing JournalPhase = "finalizing"
)

// Journal contains only recovery metadata. It never contains native bytes,
// content digests, field identifiers, summaries, or secret values.
type Journal struct {
	TransactionID     string
	Phase             JournalPhase
	WorkingDirectory  string
	ConfigurationPath string
	CreatedAt         time.Time
	Files             []JournalFile
}

// JournalFile is one target's persisted replacement identity.
type JournalFile struct {
	Ordinal        int
	Role           PathRole
	TargetPath     string
	ParentPath     string
	StageBasename  string
	Original       FileIdentity
	Parent         FileIdentity
	CandidateReady bool
	Candidate      FileIdentity
	Applied        bool
}

// RecoveryState summarizes a journal without replaying it.
type RecoveryState string

const (
	RecoveryUnapplied RecoveryState = "unapplied"
	RecoveryPartial   RecoveryState = "partial"
	RecoveryApplied   RecoveryState = "applied"
	RecoveryAmbiguous RecoveryState = "ambiguous"
)

// RecoveryFileState classifies only inode/metadata placement, never content.
type RecoveryFileState string

const (
	RecoveryFileUnstaged  RecoveryFileState = "unstaged"
	RecoveryFileUnapplied RecoveryFileState = "unapplied"
	RecoveryFileApplied   RecoveryFileState = "applied"
	RecoveryFileAmbiguous RecoveryFileState = "ambiguous"
)

// Recovery is a fresh secret-free classification of a durable journal.
type Recovery struct {
	TransactionID     string
	WorkingDirectory  string
	ConfigurationPath string
	Phase             JournalPhase
	State             RecoveryState
	Files             []RecoveryFile
}

// RecoveryFile is one classified target.
type RecoveryFile struct {
	Ordinal int
	Role    PathRole
	Path    string
	State   RecoveryFileState
}

// RecoveryResolution is an explicit administrator-directed outcome. None of
// these options replays an unapplied candidate.
type RecoveryResolution string

const (
	ResolutionDiscardUnapplied RecoveryResolution = "discard_unapplied"
	ResolutionFinalizeApplied  RecoveryResolution = "finalize_applied"
	ResolutionAdoptCurrent     RecoveryResolution = "adopt_current"
)

// RecoveryValidator validates the freshly read active file set before an
// applied or repaired current set can be accepted.
type RecoveryValidator func(context.Context, *SourceSet) error

func cloneReplacement(value Replacement) Replacement {
	value.Content = slices.Clone(value.Content)
	return value
}
